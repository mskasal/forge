"""Local single-machine Forge Hub runner (`forge serve`).

Runs the lightweight FastAPI Hub + offline Three.js web preview on localhost (or LAN
with `--lan`) without needing a Raspberry Pi or Docker.
"""

from __future__ import annotations

import os
import secrets
import sys
from pathlib import Path

from forge._paths import HUB_DIR, LOCAL_DATA_DIR
from forge.config import load_config, write_hub_config


def _ensure_local_tokens(tokens_file: Path, url: str) -> tuple[str, bool]:
    """Ensure local tokens file and workstation config.toml have a matching owner token."""
    tokens_file.parent.mkdir(parents=True, exist_ok=True)
    if tokens_file.is_file():
        for line in tokens_file.read_text(encoding="utf-8").splitlines():
            if line.strip().startswith("owner:"):
                tok = line.split(":", 1)[1].strip()
                if tok:
                    cfg = load_config().hub
                    if not cfg.token:
                        write_hub_config(url, tok)
                    return tok, False

    owner_tok = secrets.token_urlsafe(24)
    fd = os.open(tokens_file, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(f"# Auto-generated by `forge serve`\nowner:{owner_tok}\n")
    finally:
        os.chmod(tokens_file, 0o600)

    write_hub_config(url, owner_tok)
    return owner_tok, True


def serve(*, lan: bool = False, port: int = 8590, data_dir: Path | None = None) -> None:
    try:
        import uvicorn
    except ImportError:
        sys.exit("Hub dependencies not installed. Run: pip install 'forge-cad[hub]'")

    if not (HUB_DIR / "app.py").is_file():
        sys.exit(f"Hub application not found at {HUB_DIR / 'app.py'}")

    root = (data_dir or LOCAL_DATA_DIR).resolve()
    root.mkdir(parents=True, exist_ok=True)
    tokens_file = root / "tokens"
    host = "0.0.0.0" if lan else "127.0.0.1"
    display_host = "127.0.0.1"
    url = f"http://{display_host}:{port}"

    token, created = _ensure_local_tokens(tokens_file, url)

    os.environ.setdefault("FORGE_DATA", str(root / "data"))
    os.environ.setdefault("FORGE_TOKENS", str(tokens_file))

    print(f"Forge Hub listening on http://{host}:{port}/preview")
    if created:
        print(f"Created local owner token (saved to ~/.config/forge/config.toml): {token}")
    else:
        print("Using existing local token from ~/.config/forge/config.toml")
    if lan:
        print("LAN mode enabled (private CIDR subnets only; proxy headers rejected).")

    uvicorn.run("app:app", app_dir=str(HUB_DIR), host=host, port=port, log_level="info")
